type request struct {
	method, path, body string
	// statusOnly skips body comparison where the implementations
	// knowingly differ (see the call sites).
	statusOnly bool
}

func get(path string) request { return request{method: "GET", path: path} }

func post(path, body string) request { return request{method: "POST", path: path, body: body} }

type response struct {
	status      int
	contentType string
	body        any // decoded JSON, or string for other bodies
}

type server struct {
	name string
	port int
	cmd  *exec.Cmd
	out  *bytes.Buffer
}

func freePort(t *testing.T) int {
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer ln.Close()
	return ln.Addr().(*net.TCPAddr).Port
}

func buildGo(t *testing.T) string {
	bin := filepath.Join(t.TempDir(), "difit")
	if out, err := exec.Command("go", "build", "-o", bin, "difit-go/cmd/difit").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	return bin
}

func startServer(t *testing.T, name string, argv []string, dir, stdin string, args []string) *server {
	t.Helper()
	port := freePort(t)
	full := append(append(argv[1:len(argv):len(argv)], args...), "--no-open", "--keep-alive", "--port", strconv.Itoa(port))
	cmd := exec.Command(argv[0], full...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "DIFIT_CONFIG_DIR="+t.TempDir(), "DIFIT_EDITOR=", "EDITOR=")
	if stdin != "" {
		cmd.Stdin = strings.NewReader(stdin)
	}
	out := &bytes.Buffer{}
	cmd.Stdout, cmd.Stderr = out, out
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	s := &server{name: name, port: port, cmd: cmd, out: out}
	t.Cleanup(func() {
		cmd.Process.Kill()
		cmd.Wait()
	})
	deadline := time.Now().Add(15 * time.Second)
	for {
		resp, err := http.Get(s.url("/api/user-settings"))
		if err == nil {
			resp.Body.Close()
			return s
		}
		if time.Now().After(deadline) {
			t.Fatalf("%s server did not start:\n%s", name, out)
		}
		time.Sleep(50 * time.Millisecond)
	}
}

func (s *server) url(path string) string {
	return "http://127.0.0.1:" + strconv.Itoa(s.port) + path
}

func (s *server) do(t *testing.T, r request) response {
	t.Helper()
	req, err := http.NewRequest(r.method, s.url(r.path), strings.NewReader(r.body))
	if err != nil {
		t.Fatal(err)
	}
	if r.body != "" {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("%s %s %s: %v", s.name, r.method, r.path, err)
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	mediaType, _, _ := mime.ParseMediaType(resp.Header.Get("Content-Type"))
	result := response{status: resp.StatusCode, contentType: mediaType, body: string(data)}
	if mediaType == "application/json" {
		var v any
		if err := json.Unmarshal(data, &v); err != nil {
			t.Fatalf("%s %s: %v: %s", s.name, r.path, err, data)
		}
		result.body = normalize(v)
	}
	return result
}

var recentTimestamp = regexp.MustCompile(`^20\d\d-\d\d-\d\dT\d\d:\d\d:\d\d\.\d\d\dZ$`)

// normalize replaces values that legitimately differ between runs:
// timestamps generated by the server.
func normalize(v any) any {
	switch x := v.(type) {
	case map[string]any:
		for k, val := range x {
			if s, ok := val.(string); ok && (k == "createdAt" || k == "updatedAt" || k == "timestamp") && recentTimestamp.MatchString(s) {
				if ts, err := time.Parse(time.RFC3339, s); err == nil && time.Since(ts) < time.Hour {
					x[k] = "<now>"
					continue
				}
			}
			x[k] = normalize(val)
		}
	case []any:
		for i := range x {
			x[i] = normalize(x[i])
		}
	}
	return v
}

func pretty(v any) string {
	if s, ok := v.(string); ok {
		return strconv.Quote(s)
	}
	data, _ := json.MarshalIndent(v, "", "  ")
	return string(data)
}

// firstDifference describes where two decoded JSON values diverge.
func firstDifference(path string, a, b any) string {
	switch x := a.(type) {
	case map[string]any:
		y, ok := b.(map[string]any)
		if !ok {
			break
		}
		for k := range x {
			if _, ok := y[k]; !ok {
				return fmt.Sprintf("%s.%s only in reference: %s", path, k, pretty(x[k]))
			}
		}
		for k := range y {
			if _, ok := x[k]; !ok {
				return fmt.Sprintf("%s.%s only in Go: %s", path, k, pretty(y[k]))
			}
		}
		for k := range x {
			if d := firstDifference(path+"."+k, x[k], y[k]); d != "" {
				return d
			}
		}
		return ""
	case []any:
		y, ok := b.([]any)
		if !ok || len(x) != len(y) {
			break
		}
		for i := range x {
			if d := firstDifference(fmt.Sprintf("%s[%d]", path, i), x[i], y[i]); d != "" {
				return d
			}
		}
		return ""
	}
	if reflect.DeepEqual(a, b) {
		return ""
	}
	return fmt.Sprintf("%s:\n  reference: %s\n  go:        %s", path, pretty(a), pretty(b))
}

type scenario struct {
	name     string
	args     []string
	stdin    string
	requests []request
}

func runScenario(t *testing.T, ref, goBin []string, repoDir string, sc scenario) {
	refServer := startServer(t, "reference", ref, repoDir, sc.stdin, sc.args)
	goServer := startServer(t, "go", goBin, repoDir, sc.stdin, sc.args)
	for _, r := range sc.requests {
		want := refServer.do(t, r)
		got := goServer.do(t, r)
		label := r.method + " " + r.path
		if want.status != got.status {
			t.Errorf("%s: status reference %d, go %d\n  reference: %s\n  go:        %s", label, want.status, got.status, pretty(want.body), pretty(got.body))
			continue
		}
		if r.statusOnly {
			continue
		}
		if want.contentType != got.contentType {
			t.Errorf("%s: content type reference %q, go %q", label, want.contentType, got.contentType)
		}
		if d := firstDifference("$", want.body, got.body); d != "" {
			t.Errorf("%s: %s", label, d)
		}
	}
}

// buildFixture creates a repository exercising renames, deletions, binary
// files, generated files, unusual paths and branches.
func buildFixture(t *testing.T) *testrepo.Repo {
	r := testrepo.New(t)
	var app strings.Builder
	for i := 1; i <= 40; i++ {
		fmt.Fprintf(&app, "export const line%d = %d;\n", i, i)
	}
	r.Write("README.md", "# Fixture\n\nSome text.\n")
	r.Write("src/app.ts", app.String())
	r.Write("src/old-name.ts", "export const a = 1;\nexport const b = 2;\nexport const c = 3;\n")
	r.Write("deleted.txt", "goodbye\n")
	r.Write("whitespace.txt", "alpha beta\ngamma\n")
	r.Write("dir with space/ファイル.txt", "こんにちは\n")
	r.Write("assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00binary\x00")
	r.Write(".gitattributes", "gen/** linguist-generated=true\n")
	r.Write("gen/out.ts", "export {};\n")
	r.Write("package-lock.json", "{}\n")
	r.Commit("initial")

	r.Git("checkout", "-q", "-b", "feature")
	r.Write("feature.ts", "export const feature = true;\n")
	r.Commit("feature work")
	r.Git("checkout", "-q", "main")

	modified := strings.Replace(app.String(), "line3 = 3", "line3 = 300", 1)
	modified = strings.Replace(modified, "line30 = 30;\n", "line30 = 30;\nexport const inserted = true;\n", 1)
	r.Write("src/app.ts", modified)
	r.Git("mv", "src/old-name.ts", "src/new-name.ts")
	r.Write("src/new-name.ts", "export const a = 1;\nexport const b = 2;\nexport const c = 4;\n")
	r.Git("rm", "-q", "deleted.txt")
	r.Write("whitespace.txt", "alpha  beta\ngamma\n")
	r.Write("dir with space/ファイル.txt", "こんばんは\n")
	r.Write("assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00changed\x00")
	r.Write("gen/out.ts", "export const x = 1;\n")
	r.Write("package-lock.json", "{\"lockfileVersion\": 3}\n")
	r.Write("src/api.ts", "// @generated by protoc\nexport {};\n")
	r.Write("no-newline.txt", "no newline at end")
	r.Write("crlf.txt", "one\r\ntwo\r\n")
	r.Commit("main changes")
	r.Git("branch", "Zeta")
	r.Git("branch", "alpha")

	r.Write("README.md", "# Fixture\n\nSome staged text.\n")
	r.Git("add", "README.md")
	r.Write("src/app.ts", strings.Replace(modified, "line10 = 10", "line10 = 1000", 1))
	return r
}

