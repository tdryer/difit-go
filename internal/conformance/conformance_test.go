// Package conformance compares the Go server's API responses with those of
// the original Node implementation. It runs only when DIFIT_REFERENCE names
// the reference CLI script (dist/cli/index.js of an upstream build):
//
//	DIFIT_REFERENCE=$PWD/difit/dist/cli/index.js go test ./internal/conformance
