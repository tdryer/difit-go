func TestConformance(t *testing.T) {
	refScript := os.Getenv("DIFIT_REFERENCE")
	if refScript == "" {
		t.Skip("set DIFIT_REFERENCE to the upstream dist/cli/index.js to compare against the Node server")
	}
	ref := []string{"node", refScript}
	goBin := []string{buildGo(t)}
	repo := buildFixture(t)

	stdinDiff := repo.Git("diff", "HEAD~1", "HEAD") + "\n"
	stdinImports := `[{"type":"thread","id":"s1","filePath":"src/app.ts","position":{"side":"new","line":3},"body":"On stdin","createdAt":"2024-01-01T00:00:00.000Z","updatedAt":"2024-01-01T00:00:00.000Z"}]`

	scenarios := []scenario{
		{name: "default", requests: append(append(commonRequests(), commentRequests()...),
			get("/api/diff?base=main&target=feature&baseMode=merge-base"),
			get("/api/revisions"),
			get("/api/diff?base=HEAD~1&target=HEAD"),
			get("/api/diff?base=Zeta&target=alpha"),
			// simple-git words git failures differently.
			request{method: "GET", path: "/api/diff?base=HEAD&target=nope", statusOnly: true},
			get("/api/diff?base=working&target=HEAD"),
			get("/api/diff?base=staged&target=working"),
			get("/api/diff?base=HEAD&target=staged"),
			get("/api/diff?base=HEAD&target=."),
			get("/api/generated-status/src/app.ts"),
			get("/api/comments-output"),
		)},
		{name: "working", args: []string{"working"}, requests: commonRequests()},
		{name: "staged", args: []string{"staged"}, requests: commonRequests()},
		{name: "dot", args: []string{"."}, requests: commonRequests()},
		{name: "compare", args: []string{"feature", "main", "--context", "1"}, requests: commonRequests()},
		{name: "merge-base", args: []string{"feature", "main", "--merge-base"}, requests: commonRequests()},
		{name: "clean with imports", args: []string{"HEAD", "--clean", "--comment", stdinImports}, requests: []request{
			get("/api/diff"),
			get("/api/comments-json"),
			get("/api/diff?base=HEAD~1&target=HEAD"),
			get("/api/diff?base=feature&target=HEAD"),
			get("/api/comments-json"),
		}},
		{name: "stdin", args: []string{"-", "--comment", stdinImports}, stdin: stdinDiff, requests: []request{
			get("/api/diff"),
			get("/api/diff?base=other&target=thing"),
			get("/api/revisions"),
			get("/api/generated-status/src/app.ts"),
			get("/api/line-count/src/app.ts?newRef=HEAD"),
			get("/api/blob/src/app.ts"),
			get("/api/comments-json"),
			get("/api/comments-output"),
			post("/api/open-in-editor", `{"filePath":"src/app.ts"}`),
		}},
	}
	for _, sc := range scenarios {
		t.Run(sc.name, func(t *testing.T) {
			runScenario(t, ref, goBin, repo.Dir, sc)
		})
	}
}
