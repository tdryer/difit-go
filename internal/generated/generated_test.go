package generated

import "testing"

func TestPathRules(t *testing.T) {
	generated := []string{
		"Package.resolved", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "go.sum",
		"jquery.min.js", "style.min.css", "user.generated.ts", "api.gen.go", "service.pb.go",
		"schema.graphql.ts", "mock_service.go", "src/mocks/service.go",
		"node_modules/package/index.js", "dist/bundle.js", "src/__generated__/query.ts",
		"app.js.map", "a/b/gen/c.txt",
	}
	for _, p := range generated {
		if r := Check(p, nil); !r.IsGenerated || r.Reason != ReasonPath {
			t.Errorf("%s: expected path match, got %+v", p, r)
		}
	}
	for _, p := range []string{"src/index.ts", "README.md", "src/dist/x.js", "foo.generated.d-ts", "mock_service.ts"} {
		if Check(p, nil).IsGenerated {
			t.Errorf("%s: expected not generated", p)
		}
	}
}

func TestHeaderRules(t *testing.T) {
	cases := []struct {
		path   string
		lines  []string
		want   bool
		reason Reason
	}{
		{"src/unknown.ts", []string{"// @generated", "export {}"}, true, ReasonUniversal},
		{"src/client.ts", []string{"/* do not edit */"}, true, ReasonUniversal},
		{"config.yaml", []string{"# Generated by tool v1"}, true, ReasonUniversal},
		{"wire_gen.go", []string{"//go:build wireinject", "// Code generated by Wire. DO NOT EDIT."}, true, ReasonUniversal},
		{"api.ts", []string{"/* Prisma Client JS */"}, true, ReasonLanguageSpecific},
		{"Entity.php", []string{"// Doctrine ORM Generated"}, true, ReasonLanguageSpecific},
		{"Foo.java", []string{"@Generated(\"x\")"}, true, ReasonLanguageSpecific},
		{"api.py", []string{"/* Prisma Client JS */"}, false, ""},
		{"CHANGELOG.md", []string{"@generated", "DO NOT EDIT"}, false, ""},
		{"notes.markdown", []string{"Generated by"}, false, ""},
		{"src/plain.ts", []string{"export const x = 1;"}, false, ""},
	}
	for _, c := range cases {
		r := Check(c.path, func() []string { return c.lines })
		if r.IsGenerated != c.want || r.Reason != c.reason {
			t.Errorf("%s: got %+v, want %v/%s", c.path, r, c.want, c.reason)
		}
	}
}

